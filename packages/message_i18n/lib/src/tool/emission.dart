final _publicDartIdentifier = RegExp(r'^[A-Za-z\$][A-Za-z0-9\$]*$');

String messageKeyIdentifier(String key) {
  final parts = key
      .split(RegExp(r'[._-]+'))
      .where((part) => part.isNotEmpty)
      .toList();
  if (parts.isEmpty) return '';
  String firstLower(String value) =>
      '${value[0].toLowerCase()}${value.substring(1)}';
  String firstUpper(String value) =>
      '${value[0].toUpperCase()}${value.substring(1)}';
  return '${firstLower(parts.first)}${parts.skip(1).map(firstUpper).join()}';
}

String _messageKeysSource(Iterable<String> sourceKeys) {
  final byIdentifier = <String, List<String>>{};
  final invalid = <(String, String, String)>[];
  for (final key in sourceKeys.toList()..sort()) {
    final identifier = messageKeyIdentifier(key);
    final reason = switch (identifier) {
      '' => 'the generated identifier is empty',
      _ when !_publicDartIdentifier.hasMatch(identifier) =>
        'the generated name is not a public Dart identifier',
      _ when _dartKeywords.contains(identifier) =>
        'the generated name is a Dart keyword',
      _ when _objectMemberNames.contains(identifier) =>
        'the generated name cannot be declared as a static MessageKeys member',
      _ => null,
    };
    if (reason != null) {
      invalid.add((key, identifier, reason));
    } else {
      byIdentifier.putIfAbsent(identifier, () => <String>[]).add(key);
    }
  }
  final collisions =
      byIdentifier.entries.where((entry) => entry.value.length > 1).toList()
        ..sort((a, b) => a.key.compareTo(b.key));
  if (invalid.isNotEmpty || collisions.isNotEmpty) {
    final lines = <String>['Cannot generate MessageKeys.'];
    if (invalid.isNotEmpty) {
      lines.add('Invalid generated identifiers:');
      for (final entry in invalid) {
        lines.add(
          '- catalog key ${dartLiteral(entry.$1)} -> '
          '${dartLiteral(entry.$2)}: ${entry.$3}',
        );
      }
    }
    for (final collision in collisions) {
      lines.add(
        'Message key identifier collision: MessageKeys.${collision.key}',
      );
      for (final key in collision.value..sort()) {
        lines.add('- ${dartLiteral(key)}');
      }
    }
    lines.add('Rename the catalog keys and run build_runner again.');
    throw FormatException(lines.join('\n'));
  }
  final entries = byIdentifier.entries.toList()
    ..sort((a, b) => a.key.compareTo(b.key));
  return '''abstract final class MessageKeys {
${entries.map((entry) => '  static const String ${entry.key} = ${dartLiteral(entry.value.single)};').join('\n')}
}
''';
}

Map<String, String> emitCatalog(MessageCatalog source) {
  final issues = validateCatalog(source);
  if (issues.isNotEmpty) throw FormatException(issues.join('\n'));
  final catalog = normalizeCatalog(source);
  final locales = catalog.supportedLocales;
  final keys = catalog.messages.keys.toList()..sort();
  if (locales.map(localeToken).toSet().length != locales.length) {
    throw const FormatException('Locale filename collision');
  }
  final outputs = <String, String>{};
  for (final locale in locales.toList()..sort()) {
    final token = localeToken(locale);
    outputs['messages_$token.g.dart'] =
        '''$generatedMarker
Map<String, String> ${factoryName(locale)}() => <String, String>{
${keys.map((key) => '  ${dartLiteral(key)}: ${dartLiteral(catalog.messages[key]!.translations[locale]!)},').join('\n')}
};
''';
  }
  outputs['message_loader.g.dart'] =
      '''$generatedMarker
import 'package:message_i18n/message_i18n.dart';
${(locales.toList()..sort()).map((l) => "import 'messages_${localeToken(l)}.g.dart';").join('\n')}

const supportedMessageLocales = <String>[${locales.map(dartLiteral).join(', ')}];
const defaultMessageLocale = ${dartLiteral(catalog.defaultLocale)};

String resolveGeneratedLocale(String requested) => resolveLocale(requested, supportedMessageLocales, defaultMessageLocale);

GeneratedLocaleMessages loadGeneratedMessages(String requested) {
  final locale = resolveGeneratedLocale(requested);
  return switch (locale) {
${locales.map((l) => '    ${dartLiteral(l)} => GeneratedLocaleMessages(locale, ${factoryName(l)}()),').join('\n')}
    _ => throw StateError('Invalid generated locale'),
  };
}

MessageResolver createMessageResolver({required String selected, MessageDiagnosticCallback? onDiagnostic}) => MessageResolver.fromLoader(selected: selected, loader: loadGeneratedMessages, onDiagnostic: onDiagnostic);
''';
  final logical = {
    'defaultLocale': catalog.defaultLocale,
    'supportedLocales': locales,
    'messages': {
      for (final key in keys)
        key: {
          for (final locale in locales.toList()..sort())
            locale: catalog.messages[key]!.translations[locale],
        },
    },
  };
  outputs[manifestName] =
      '${const JsonEncoder.withIndent('  ').convert({'schemaVersion': 1, 'catalogFingerprint': sha256.convert(utf8.encode(jsonEncode(logical))).toString(), 'locales': locales, 'keyCount': keys.length, 'ownedFiles': outputs.keys.toList()..sort()})}\n';
  return outputs;
}

/// Emits a self-contained runtime library, without importing the source catalog.
String emitStandaloneCatalog(MessageCatalog catalog) {
  final files = emitCatalog(catalog);
  final messageKeys = _messageKeysSource(catalog.messages.keys);
  final loader = files['message_loader.g.dart']!;
  final localeFiles =
      files.keys
          .where(
            (name) => name.startsWith('messages_') && name.endsWith('.g.dart'),
          )
          .toList()
        ..sort();
  var standalone = loader;
  for (final name in localeFiles) {
    standalone = standalone.replaceFirst("import '$name';\n", '');
  }
  return '$standalone\n$messageKeys\n${localeFiles.map((name) => files[name]!.replaceFirst('$generatedMarker\n', '')).join('\n')}';
}
