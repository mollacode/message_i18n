String dartLiteral(String value) => jsonEncode(value).replaceAll(r'$', r'\$');
String localeToken(String locale) => locale.toLowerCase().replaceAll('-', '_');

String factoryName(String locale) =>
    'load${locale.split('-').map((s) => s[0].toUpperCase() + s.substring(1)).join()}Messages';

